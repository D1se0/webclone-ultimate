function rotr(x: number, n: number): number {
  return (x >>> n) | (x << (32 - n));
}

/** SHA-256 puro (fallback para contextos no seguros donde crypto.subtle no existe). */
export function sha256HexSync(input: Uint8Array): string {
  const h = new Uint32Array([
    0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19,
  ]);
  const bitLen = input.length * 8;
  const withPad = new Uint8Array((((input.length + 8) >> 6) + 1) << 6);
  withPad.set(input);
  withPad[input.length] = 0x80;
  // Longitud en bits como big-endian a 64 bits (suficiente hasta 2^53 bytes).
  const dataLen = withPad.length;
  const hi = Math.floor(bitLen / 0x100000000);
  const lo = bitLen >>> 0;
  withPad[dataLen - 8] = (hi >>> 24) & 0xff;
  withPad[dataLen - 7] = (hi >>> 16) & 0xff;
  withPad[dataLen - 6] = (hi >>> 8) & 0xff;
  withPad[dataLen - 5] = hi & 0xff;
  withPad[dataLen - 4] = (lo >>> 24) & 0xff;
  withPad[dataLen - 3] = (lo >>> 16) & 0xff;
  withPad[dataLen - 2] = (lo >>> 8) & 0xff;
  withPad[dataLen - 1] = lo & 0xff;

  const w = new Uint32Array(64);
  for (let offset = 0; offset < dataLen; offset += 64) {
    for (let i = 0; i < 16; i++) {
      const j = offset + i * 4;
      w[i] = (withPad[j] << 24) | (withPad[j + 1] << 16) | (withPad[j + 2] << 8) | withPad[j + 3];
    }
    for (let i = 16; i < 64; i++) {
      const s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >>> 3);
      const s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >>> 10);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) >>> 0;
    }
    let a = h[0], b = h[1], c = h[2], d = h[3], e = h[4], f = h[5], g = h[6], hh = h[7];
    for (let i = 0; i < 64; i++) {
      const S1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
      const ch = (e & f) ^ (~e & g);
      const t1 = (hh + S1 + ch + K[i] + w[i]) >>> 0;
      const S0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (S0 + maj) >>> 0;
      hh = g; g = f; f = e; e = (d + t1) >>> 0;
      d = c; c = b; b = a; a = (t1 + t2) >>> 0;
    }
    h[0] = (h[0] + a) >>> 0; h[1] = (h[1] + b) >>> 0; h[2] = (h[2] + c) >>> 0; h[3] = (h[3] + d) >>> 0;
    h[4] = (h[4] + e) >>> 0; h[5] = (h[5] + f) >>> 0; h[6] = (h[6] + g) >>> 0; h[7] = (h[7] + hh) >>> 0;
  }
  const out = new Uint8Array(32);
  for (let i = 0; i < 8; i++) {
    out[i * 4] = (h[i] >>> 24) & 0xff;
    out[i * 4 + 1] = (h[i] >>> 16) & 0xff;
    out[i * 4 + 2] = (h[i] >>> 8) & 0xff;
    out[i * 4 + 3] = h[i] & 0xff;
  }
  return toHex(out);
}

export async function sha256Hex(input: Uint8Array): Promise<string> {
  const subtle = (globalThis.crypto as Crypto | undefined)?.subtle;
  if (subtle) {
    try {
      const digest = await subtle.digest('SHA-256', input as unknown as BufferSource);
      return toHex(new Uint8Array(digest));
    } catch {
      /* cae al fallback */
    }
  }
  return sha256HexSync(input);
}

export function shortHash(input: string): string {
  const bytes = new TextEncoder().encode(input);
  return sha256HexSync(bytes).slice(0, 12);
}

let crcTable: Uint32Array | null = null;

/** CRC-32 (IEEE 802.3), el mismo que usa ZIP. */
export function crc32(bytes: Uint8Array): number {
  if (!crcTable) {
    crcTable = new Uint32Array(256);
    for (let n = 0; n < 256; n++) {
      let c = n;
      for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
      crcTable[n] = c >>> 0;
    }
  }
  let crc = 0xffffffff;
  for (let i = 0; i < bytes.length; i++) crc = (crc >>> 8) ^ crcTable[(crc ^ bytes[i]) & 0xff];
  return (crc ^ 0xffffffff) >>> 0;
}
